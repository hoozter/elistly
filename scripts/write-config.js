/**
 * Writes config.js from environment variables (for Cloudflare Pages or CI).
 * Preferred env vars: ELISTLY_BACKEND_PROVIDER, ELISTLY_BACKEND_URL, ELISTLY_PUBLIC_KEY, ELISTLY_API_URL.
 * Backward-compatible fallbacks: SUPABASE_URL, SUPABASE_ANON_KEY.
 * Output: config.js in project root with provider-neutral names plus legacy aliases.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const provider = process.env.ELISTLY_BACKEND_PROVIDER || 'supabase';
const url = process.env.ELISTLY_BACKEND_URL || process.env.SUPABASE_URL || '';
const publicKey = process.env.ELISTLY_PUBLIC_KEY || process.env.SUPABASE_ANON_KEY || '';
const apiUrl = process.env.ELISTLY_API_URL || '';

const content = `/**
 * Elistly config – generated by scripts/write-config.js from env. Do not commit if it contains real keys.
 * Env vars used: ELISTLY_BACKEND_PROVIDER, ELISTLY_BACKEND_URL, ELISTLY_PUBLIC_KEY, ELISTLY_API_URL
 * Legacy fallbacks: SUPABASE_URL, SUPABASE_ANON_KEY
 */
(function () {
  'use strict';
  window.ELISTLY_BACKEND_PROVIDER = ${JSON.stringify(provider)};
  window.ELISTLY_BACKEND_URL = ${JSON.stringify(url)};
  window.ELISTLY_PUBLIC_KEY = ${JSON.stringify(publicKey)};
  window.ELISTLY_API_URL = ${JSON.stringify(apiUrl)};
  window.SUPABASE_URL = window.ELISTLY_BACKEND_URL;
  window.SUPABASE_ANON_KEY = window.ELISTLY_PUBLIC_KEY;
})();
`;

fs.writeFileSync(path.join(root, 'config.js'), content, 'utf8');
console.log('Wrote config.js from env (ELISTLY_BACKEND_PROVIDER, ELISTLY_BACKEND_URL, ELISTLY_PUBLIC_KEY, ELISTLY_API_URL).');
